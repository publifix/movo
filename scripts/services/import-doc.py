#!/usr/bin/env python3
"""Import the Services copy from the official document into the site, verbatim.

Source: docs/MOVO-Servicios-textos-ES-EN-y-direccion-de-diseno.docx (owner's document; do not
rewrite its texts). This script reads its tables and paragraphs and writes:

  src/i18n/es.json, src/i18n/en.json  → the "services" key (every visible Services string)
  src/data/services.json              → structure: pillars, services, slugs, anchors, colors,
                                         Work filters, process steps and format stages

Texts marked [CONFIRMAR] are kept as they are (the site styles the marker) until MOVO validates them.
Run again whenever the document changes:

  python3 scripts/services/import-doc.py [path/to/document.docx]
"""
import json
import re
import sys
from pathlib import Path

import docx

ROOT = Path(__file__).resolve().parents[2]
DOC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'docs/MOVO-Servicios-textos-ES-EN-y-direccion-de-diseno.docx'

# From the document's design direction ("Color por pilar") and anchors line.
PILLARS = [
    {'id': 'brand', 'number': '01', 'color': 'volt', 'anchor': {'es': 'marca', 'en': 'brand'}},
    {'id': 'content', 'number': '02', 'color': 'magenta', 'anchor': {'es': 'contenido', 'en': 'content'}},
    {'id': 'explain', 'number': '03', 'color': 'violet', 'anchor': {'es': 'explicar', 'en': 'explain'}},
]
# "Filtro en Trabajo" column → category ids of src/data/reels.json
CATEGORY = {'Branding': 'branding', 'Social': 'social', 'Publicidad': 'advertising', 'Explainer': 'explainer'}
SERVICE_IDS = ['animated-logo', 'motion-identity', 'brand-kit', 'reels', 'ads', 'campaigns', 'monthly-plan',
               'explainers', 'product', 'events']
STEP_IDS = ['brief', 'script', 'styleframes', 'animation', 'delivery']
# Formats table rows → ids. The table names the formats in Spanish only (except "A la medida / Custom");
# the English names below are the ratio names, not copy from the document.
FORMAT_IDS = ['vertical', 'square', 'landscape', 'custom']
FORMAT_EN_NAMES = {'vertical': 'Vertical 9:16', 'square': 'Square 1:1 & 4:5', 'landscape': 'Horizontal 16:9'}
# Stages of the morphing frame (Formats): ratio → which table row explains it.
FORMAT_STAGES = [
    {'ratio': '9:16', 'w': 9, 'h': 16, 'format': 'vertical'},
    {'ratio': '1:1', 'w': 1, 'h': 1, 'format': 'square'},
    {'ratio': '4:5', 'w': 4, 'h': 5, 'format': 'square'},
    {'ratio': '16:9', 'w': 16, 'h': 9, 'format': 'landscape'},
    {'ratio': '32:9', 'w': 32, 'h': 9, 'format': 'custom'},
]


def split2(text, sep=' / '):
    a, b = text.split(sep, 1)
    return a.strip(), b.strip()


def rows(table, skip_header=True):
    out = [[c.text.strip() for c in r.cells] for r in table.rows]
    return out[1:] if skip_header else out


def kv(table):
    return {r[0]: r[1:] for r in rows(table)}


def main():
    d = docx.Document(str(DOC))
    T = d.tables
    P = [p.text.strip() for p in d.paragraphs]
    es, en = {}, {}

    # --- architecture (table 0): services, slugs, Work filter ---
    arch = rows(T[0])
    structure = {'_note': 'GENERATED by scripts/services/import-doc.py from the Services document. Do not edit by hand.',
                 'source': str(DOC.relative_to(ROOT)), 'pillars': []}
    for p in PILLARS:
        structure['pillars'].append({**p, 'workFilter': [], 'services': []})
    for i, (pillar, name_es, name_en, slugs, filt) in enumerate(arch):
        pi = int(pillar[:2]) - 1
        slug_es, slug_en = split2(slugs)
        cat = CATEGORY[filt]
        pl = structure['pillars'][pi]
        pl['services'].append({'id': SERVICE_IDS[i], 'slug': {'es': slug_es, 'en': slug_en}, 'category': cat})
        if cat not in pl['workFilter']:
            pl['workFilter'].append(cat)

    # --- home section (table 1) ---
    h = kv(T[1])
    for lang, col in (('es', 0), ('en', 1)):
        S = es if lang == 'es' else en
        S['label'] = h['Etiqueta'][col]
        S['home'] = {'heading': h['Titular'][col], 'intro': h['Intro'][col],
                     'more': h['Enlace de cada pilar'][col], 'cta': h['Botón'][col]}
        S['pillars'] = {}
        for p in PILLARS:
            n = p['number']
            S['pillars'][p['id']] = {
                'title': h[f'Pilar {n} · título'][col],
                'phrase': h[f'Pilar {n} · frase'][col],
                'tags': [t.strip() for t in h[f'Pilar {n} · etiquetas'][col].split(' · ')],
                'services': {},
            }

    # --- page header (table 2) ---
    hd = kv(T[2])
    for S, col in ((es, 0), (en, 1)):
        S['page'] = {'label': hd['Etiqueta'][col], 'h1': hd['Titular (H1)'][col], 'subtitle': hd['Subtítulo'][col]}

    # --- pillars: intros, links (paragraphs) and services (tables 3–5) ---
    intros_es = [p.split('ES — intro: ', 1)[1] for p in P if p.startswith('ES — intro: ')]
    intros_en = [p.split('EN — intro: ', 1)[1] for p in P if p.startswith('EN — intro: ')]
    links = [p.split('Enlace: ', 1)[1].split(' → ', 1)[0] for p in P if p.startswith('Enlace: ')]
    si = 0
    for k, p in enumerate(PILLARS):
        link_es, link_en = split2(links[k])
        es['pillars'][p['id']].update(intro=intros_es[k], link=link_es)
        en['pillars'][p['id']].update(intro=intros_en[k], link=link_en)
        for name, desc_es, desc_en, deliv in rows(T[3 + k]):
            sid = SERVICE_IDS[si]
            si += 1
            n_es, n_en = split2(name)
            d_es, d_en = split2(deliv)
            es['pillars'][p['id']]['services'][sid] = {'name': n_es, 'description': desc_es, 'deliverables': d_es}
            en['pillars'][p['id']]['services'][sid] = {'name': n_en, 'description': desc_en, 'deliverables': d_en}

    # --- how we work (paragraphs + table 6) ---
    pes = next(p for p in P if p.startswith('ES — título: Cinco'))
    pen = next(p for p in P if p.startswith('EN — título: Five'))
    for S, para, tag in ((es, pes, 'ES'), (en, pen, 'EN')):
        title, intro = para.split(f'{tag} — título: ', 1)[1].split(f' {tag} — intro: ', 1)
        S['process'] = {'title': title.strip(), 'intro': intro.strip(), 'steps': {}}
    for i, (num, st_es, tx_es, st_en, tx_en) in enumerate(rows(T[6])):
        es['process']['steps'][STEP_IDS[i]] = {'number': num, 'name': st_es, 'text': tx_es}
        en['process']['steps'][STEP_IDS[i]] = {'number': num, 'name': st_en, 'text': tx_en}

    # --- formats (paragraphs + table 7) ---
    ft = next(p for p in P if p.startswith('ES — título: Listo'))
    t_es, t_en = ft.split('ES — título: ', 1)[1].split(' EN — título: ', 1)
    fn = next(p for p in P if p.startswith('ES — nota de archivos'))
    n_es, n_en = fn.split('ES — nota de archivos: ', 1)[1].split(' EN — file note: ', 1)
    es['formats'] = {'title': t_es.strip(), 'note': n_es.strip(), 'items': {}}
    en['formats'] = {'title': t_en.strip(), 'note': n_en.strip(), 'items': {}}
    for i, (name, use_es, use_en) in enumerate(rows(T[7])):
        fid = FORMAT_IDS[i]
        if ' / ' in name:
            name_es, name_en = split2(name)
        else:
            name_es, name_en = name, FORMAT_EN_NAMES[fid]
        es['formats']['items'][fid] = {'name': name_es, 'use': use_es}
        en['formats']['items'][fid] = {'name': name_en, 'use': use_en}

    # --- FAQ (table 8) ---
    es['faq'] = {'items': []}
    en['faq'] = {'items': []}
    for q_es, a_es, q_en, a_en in rows(T[8]):
        es['faq']['items'].append({'q': q_es, 'a': a_es})
        en['faq']['items'].append({'q': q_en, 'a': a_en})

    # --- closing (table 9) and SEO (table 10) ---
    c = kv(T[9])
    m = kv(T[10])
    for S, col in ((es, 0), (en, 1)):
        S['closing'] = {'title': c['Titular'][col], 'cta': c['Botón'][col]}
        S['meta'] = {'title': m['Title'][col], 'description': m['Description'][col]}

    structure['process'] = STEP_IDS
    structure['formats'] = FORMAT_STAGES

    (ROOT / 'src/data/services.json').write_text(json.dumps(structure, ensure_ascii=False, indent=2) + '\n')
    for lang, S in (('es', es), ('en', en)):
        f = ROOT / f'src/i18n/{lang}.json'
        data = json.loads(f.read_text())
        data['services'] = {'_note': 'GENERATED from the Services document by scripts/services/import-doc.py. '
                                     'Do not edit by hand: edit the document and re-run the script.', **S}
        f.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')
    print('ok: services strings (es, en) and src/data/services.json')


if __name__ == '__main__':
    main()
